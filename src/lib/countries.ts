/** Look up a country by name (case-insensitive) and return its flag emoji, or null */
export function getFlagForCountry(name: string | null | undefined): string | null {
  if (!name) return null;
  const lower = name.toLowerCase();
  const match = COUNTRIES.find(c => c.name.toLowerCase() === lower);
  return match?.flag ?? null;
}

